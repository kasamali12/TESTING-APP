const { chromium } = require('playwright'); const path = require('path');
const ok = (n, c, x) => { console.log((c ? 'PASS ' : 'FAIL ') + n + (x ? '  ' + x : '')); if (!c) process.exitCode = 1; };
(async () => {
  const b = await chromium.launch(); const c = await b.newContext({ viewport: { width: 390, height: 780 }, isMobile: true, hasTouch: true });
  await c.route('**/*', r => { const u = r.request().url(); /^(file|data|blob|about):/.test(u) ? r.continue() : r.abort(); });
  await c.addInitScript(() => { try { localStorage.setItem('sd_terms_v2', '1'); localStorage.setItem('sd_intro_v2', '1'); } catch (e) {} });
  const p = await c.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.goto('file://' + path.resolve(process.env.APP || '../index.html'), { waitUntil: 'load' }); await p.waitForTimeout(2200);
  await p.evaluate(() => { document.getElementById('sd-auth-ov').style.display = 'none'; document.getElementById('sd-app-wrapper').style.display = ''; navTo('home'); });
  await p.waitForTimeout(1200);
  ok('top-bar file button is named', await p.evaluate(() => { const e = document.querySelector('.tb-act'); return !e || e.getAttribute('aria-label') === 'Open file'; }));
  await p.evaluate(() => navTo('set')); await p.waitForTimeout(1000);
  const names = await p.evaluate(() => ['qfz-slider', 'reminder-time-inp', 'set-examdate-neet', 'pm-pool-input', 'ai-custom-prompt', 'ai-key-anthropic', 'mcqd-deck-search'].map(i => i + '=' + document.getElementById(i).getAttribute('aria-label')).join(' | '));
  console.log(names);
  ok('settings inputs named from their visible labels', !/=null/.test(names));
  await p.evaluate(() => toast('Answer saved', 'success')); await p.waitForTimeout(300);
  ok('toast is spoken through the status region', await p.evaluate(() => document.getElementById('sd-live').textContent === 'Answer saved'));
  await p.evaluate(() => toast('Could not save', 'error')); await p.waitForTimeout(300);
  ok('errors use the alert region', await p.evaluate(() => document.getElementById('sd-live-err').textContent === 'Could not save'));
  ok('toast still shows on screen', await p.evaluate(() => !!document.querySelector('.toast')));
  ok('no page errors', errs.length === 0, errs.join('|'));
  await b.close();
})();
